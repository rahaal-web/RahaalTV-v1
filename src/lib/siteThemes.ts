const SITE_THEME_ID_SET = new Set<string>(SITE_THEME_IDS);

export function normalizeSiteThemeId(raw: unknown): SiteThemeId {
  if (typeof raw === 'string') {
    const clean = raw.trim();
    if (SITE_THEME_ID_SET.has(clean)) {
      return clean as SiteThemeId;
    }
  }
  return 'default';
}

export function getSiteThemeDefinition(themeId?: SiteThemeId | string | null): SiteThemeDefinition {
  const normalized = normalizeSiteThemeId(themeId);
  return SITE_THEMES.find((t) => t.id === normalized) || SITE_THEMES[0];
}

export function buildSiteThemeCssVars(themeId?: SiteThemeId | string | null): Record<string, string> {
  const t = getSiteThemeDefinition(themeId);
  return {
    '--rtv-site-bg': t.bg,
    '--rtv-site-surface': t.surface,
    '--rtv-site-surface-2': t.surface2,
    '--rtv-site-header': t.header,
    '--rtv-site-footer': t.footer,
    '--rtv-site-accent': t.accent,
    '--rtv-site-accent-hover': t.accentHover,
    '--rtv-site-gold': t.gold,
    '--rtv-site-success': t.success,
    '--rtv-site-text': t.text,
    '--rtv-site-muted': t.muted,
    '--rtv-site-border': t.border,
    '--rtv-site-glow': t.glow,
    '--rtv-site-radius': `${t.radiusPx}px`,
  };
}

export function loadStoredSiteThemeId(): SiteThemeId {
  if (typeof window === 'undefined') return 'default';
  try {
    return normalizeSiteThemeId(window.localStorage.getItem(SITE_THEME_STORAGE_KEY));
  } catch {
    return 'default';
  }
}

export function saveStoredSiteThemeId(themeId: SiteThemeId): SiteThemeId {
  const normalized = normalizeSiteThemeId(themeId);
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(SITE_THEME_STORAGE_KEY, normalized);
    } catch {
      // Ignore storage quota errors
    }
  }
  return normalized;
}
